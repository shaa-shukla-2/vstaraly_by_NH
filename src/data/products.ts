export function getProduct(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string) {
  return products.find((p) => p.id === id);
}

export function getCollection(slug: string) {
  return collections.find((c) => c.slug === slug);
}

export function productsForCollection(slug: string) {
  if (slug === "new-arrivals") {
    return products.filter((p) => p.collections.includes("new-arrivals") || p.badges.includes("New"));
  }
  if (slug === "sale") {
    return products.filter((p) => p.compareAtPrice || p.collections.includes("sale"));
  }
  if (slug === "best-sellers") {
    return products.filter((p) => p.badges.includes("Bestseller") || p.collections.includes("best-sellers"));
  }
  return products.filter(
    (p) => p.collections.includes(slug) || p.category === slug || p.occasions.includes(slug),
  );
}

export function searchProducts(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return products.filter((p) =>
    [p.name, p.designer, p.category, p.fabric, ...p.occasions].join(" ").toLowerCase().includes(q),
  );
}

